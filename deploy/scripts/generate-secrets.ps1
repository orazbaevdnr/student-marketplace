# Generates strong secrets for deploy/.env.prod.
#
#   .\scripts\generate-secrets.ps1                 # print the values
#   .\scripts\generate-secrets.ps1 -OutFile .env.prod
#
# The values are URL-safe base64 without padding, so they are safe inside .env files
# and inside JDBC URLs.

param(
    [string]$OutFile = "",
    [string]$Domain = "marketplace.kbtu.kz",
    [string]$AdminEmail = "admin@kbtu.kz"
)

function New-Secret([int]$Bytes) {
    $buffer = New-Object byte[] $Bytes
    # RandomNumberGenerator.Fill() is .NET Core only; GetBytes() works on Windows PowerShell 5.1 too.
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try { $rng.GetBytes($buffer) } finally { $rng.Dispose() }
    [Convert]::ToBase64String($buffer).TrimEnd('=').Replace('+', '-').Replace('/', '_')
}

$dbPassword = New-Secret 32
$jwtSecret = New-Secret 48
$adminPassword = New-Secret 18

$content = @"
# Generated by deploy/scripts/generate-secrets.ps1 on $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')
# Keep this file private. Never commit it.

DOMAIN=$Domain
HTTP_PORT=80
HTTPS_PORT=443

DB_NAME=marketplace
DB_USER=marketplace
DB_PASSWORD=$dbPassword

JWT_SECRET=$jwtSecret
JWT_TTL_MINUTES=60

ADMIN_EMAIL=$AdminEmail
ADMIN_PASSWORD=$adminPassword

ALLOWED_EMAIL_DOMAIN=kbtu.kz
FIREBASE_PROJECT_ID=student-marketplace-1b107
CORS_ORIGINS=https://$Domain

# Fill these in from the Firebase console (Project settings -> Your apps).
VITE_FIREBASE_API_KEY=
VITE_FIREBASE_AUTH_DOMAIN=student-marketplace-1b107.firebaseapp.com
VITE_FIREBASE_PROJECT_ID=student-marketplace-1b107
VITE_FIREBASE_APP_ID=

BACKUP_KEEP_DAYS=14
"@

if ($OutFile) {
    $target = [System.IO.Path]::GetFullPath($OutFile)
    if (Test-Path $target) {
        Write-Error "Refusing to overwrite existing file: $target"
        exit 1
    }
    # Write UTF-8 without BOM: a BOM can confuse .env parsers.
    [System.IO.File]::WriteAllText($target, $content, (New-Object System.Text.UTF8Encoding($false)))
    Write-Output "Secrets written to $target"
    Write-Output "Next: fill VITE_FIREBASE_* from the Firebase console, then run:"
    Write-Output "  docker compose --env-file .env.prod -f docker-compose.prod.yml up -d --build"
} else {
    Write-Output $content
}
