-- Student Marketplace: the five tables from the Task 9 database plan.
-- Written to run unchanged on PostgreSQL and on H2 (MODE=PostgreSQL).

CREATE TABLE users (
    user_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    university_email VARCHAR(255) NOT NULL,
    password_hash    VARCHAR(100) NOT NULL,
    display_name     VARCHAR(100) NOT NULL,
    role             VARCHAR(20)  NOT NULL,
    is_active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_users_email UNIQUE (university_email),
    CONSTRAINT ck_users_role CHECK (role IN ('STUDENT', 'ADMIN'))
);

CREATE TABLE categories (
    category_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(60)  NOT NULL,
    description   VARCHAR(255),
    is_active     BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_categories_name UNIQUE (category_name)
);

-- Listing IDs look like L-101, L-102 ... L-1000: the number part simply grows, so the
-- "only 999 listings" problem of the L-### format from Task 7 does not exist.
CREATE SEQUENCE listing_id_seq START WITH 101 INCREMENT BY 1;

CREATE TABLE listings (
    listing_id       VARCHAR(16)  PRIMARY KEY,
    seller_id        BIGINT       NOT NULL,
    category_id      BIGINT       NOT NULL,
    title            VARCHAR(120) NOT NULL,
    description      VARCHAR(2000),
    price_kzt        INTEGER      NOT NULL,
    status           VARCHAR(20)  NOT NULL,
    created_at       DATE         NOT NULL,
    last_updated     DATE         NOT NULL,
    reminder_sent_on DATE,
    version          BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT fk_listings_seller   FOREIGN KEY (seller_id)   REFERENCES users (user_id),
    CONSTRAINT fk_listings_category FOREIGN KEY (category_id) REFERENCES categories (category_id),
    CONSTRAINT ck_listings_id     CHECK (listing_id LIKE 'L-%'),
    CONSTRAINT ck_listings_price  CHECK (price_kzt > 0),
    CONSTRAINT ck_listings_status CHECK (status IN ('AVAILABLE', 'RESERVED', 'SOLD', 'HIDDEN')),
    CONSTRAINT ck_listings_dates  CHECK (last_updated >= created_at)
);

CREATE INDEX idx_listings_status_updated ON listings (status, last_updated);
CREATE INDEX idx_listings_category        ON listings (category_id);
CREATE INDEX idx_listings_seller          ON listings (seller_id);
CREATE INDEX idx_listings_price           ON listings (price_kzt);

CREATE TABLE listing_photos (
    photo_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id  VARCHAR(16)  NOT NULL,
    file_path   VARCHAR(255) NOT NULL,
    sort_order  INTEGER      NOT NULL,
    uploaded_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_photos_listing FOREIGN KEY (listing_id) REFERENCES listings (listing_id) ON DELETE CASCADE,
    CONSTRAINT uq_photos_order UNIQUE (listing_id, sort_order),
    CONSTRAINT ck_photos_order CHECK (sort_order >= 1)
);

-- UNIQUE (listing_id): one listing can be sold only once, even under concurrent requests.
CREATE TABLE purchases (
    purchase_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id      VARCHAR(16) NOT NULL,
    buyer_id        BIGINT      NOT NULL,
    final_price_kzt INTEGER     NOT NULL,
    purchased_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_purchases_listing UNIQUE (listing_id),
    CONSTRAINT fk_purchases_listing FOREIGN KEY (listing_id) REFERENCES listings (listing_id),
    CONSTRAINT fk_purchases_buyer   FOREIGN KEY (buyer_id)   REFERENCES users (user_id),
    CONSTRAINT ck_purchases_price   CHECK (final_price_kzt > 0)
);

CREATE INDEX idx_purchases_buyer ON purchases (buyer_id);
