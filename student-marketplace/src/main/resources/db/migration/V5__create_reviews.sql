-- Seller reviews. Reviews are written by one student about another student's listing,
-- so they are shared by every device instead of living in the browser's localStorage.

CREATE TABLE reviews (
    review_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id   BIGINT       NOT NULL,
    reviewer_id BIGINT       NOT NULL,
    listing_id  VARCHAR(16)  NOT NULL,
    rating      INTEGER      NOT NULL,
    tags        VARCHAR(255) NOT NULL DEFAULT '',
    comment     VARCHAR(2000),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_reviews_seller   FOREIGN KEY (seller_id)   REFERENCES users (user_id),
    CONSTRAINT fk_reviews_reviewer FOREIGN KEY (reviewer_id) REFERENCES users (user_id),
    CONSTRAINT fk_reviews_listing  FOREIGN KEY (listing_id)  REFERENCES listings (listing_id) ON DELETE CASCADE,
    CONSTRAINT uq_reviews_reviewer_listing UNIQUE (reviewer_id, listing_id),
    CONSTRAINT ck_reviews_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT ck_reviews_not_self CHECK (reviewer_id <> seller_id)
);

CREATE INDEX idx_reviews_seller   ON reviews (seller_id, created_at);
CREATE INDEX idx_reviews_reviewer ON reviews (reviewer_id, created_at);
CREATE INDEX idx_reviews_listing  ON reviews (listing_id);
