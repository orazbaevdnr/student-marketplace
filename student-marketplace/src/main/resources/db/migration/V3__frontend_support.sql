UPDATE categories SET slug = 'electronics' WHERE category_name = 'Electronics';
UPDATE categories SET slug = 'clothes'     WHERE category_name = 'Clothes';
UPDATE categories SET slug = 'furniture'   WHERE category_name = 'Furniture';
UPDATE categories SET slug = 'sports'      WHERE category_name = 'Sports';
UPDATE categories SET slug = 'other'       WHERE category_name = 'Other';
-- any category an administrator added before this migration
UPDATE categories SET slug = LOWER(REPLACE(category_name, ' ', '_')) WHERE slug IS NULL;

