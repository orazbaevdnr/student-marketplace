-- ---------- listings: condition and seller contact ----------
ALTER TABLE listings ADD COLUMN item_condition VARCHAR(20) NOT NULL DEFAULT 'GOOD';
ALTER TABLE listings ADD COLUMN contact VARCHAR(100);
ALTER TABLE listings ADD CONSTRAINT ck_listings_condition
    CHECK (item_condition IN ('NEW', 'LIKE_NEW', 'GOOD', 'FAIR'));

-- ---------- users: profile and Firebase ----------
ALTER TABLE users ADD COLUMN firebase_uid   VARCHAR(128);
ALTER TABLE users ADD COLUMN faculty        VARCHAR(100);
ALTER TABLE users ADD COLUMN study_year     INTEGER;
ALTER TABLE users ADD COLUMN telegram       VARCHAR(64);
ALTER TABLE users ADD COLUMN avatar_url     VARCHAR(500);
ALTER TABLE users ADD COLUMN email_verified BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE users ADD CONSTRAINT ck_users_year CHECK (study_year IS NULL OR (study_year BETWEEN 1 AND 8));
CREATE UNIQUE INDEX uq_users_firebase_uid ON users (firebase_uid);

-- ---------- favorites ----------
CREATE TABLE favorites (
    favorite_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL,
    listing_id  VARCHAR(16) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_favorites UNIQUE (user_id, listing_id),
    CONSTRAINT fk_favorites_user    FOREIGN KEY (user_id)    REFERENCES users (user_id)       ON DELETE CASCADE,
    CONSTRAINT fk_favorites_listing FOREIGN KEY (listing_id) REFERENCES listings (listing_id) ON DELETE CASCADE
);

CREATE INDEX idx_favorites_user ON favorites (user_id, created_at);
